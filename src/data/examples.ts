// Pick a random example for a word based on its pos
export function getExample(word: string, pos: string): string {
  const isVerb = /動|自|他/.test(pos);
  const isAdj = /形/.test(pos);
  const pool = isVerb ? verbExamples : isAdj ? adjExamples : nounExamples;
  return pool[Math.floor(Math.random() * pool.length)].replace(/\[W\]/g, `【${word}】`);
}
